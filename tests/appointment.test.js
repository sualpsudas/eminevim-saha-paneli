const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const A = require('../appointment.js');

let t = A.create({tip:'ziyaret',repId:'s2',durum:'netlesti',gunYazi:'Cuma',saat:'18:00',yer:'Üsküdar'});
const proposal = A.propose(t,{gunYazi:'Cumartesi',saat:'19:00',yer:'Yeni adres',repId:'s3'});
assert.equal(proposal.saat,'18:00','Öneri mevcut saati değiştirmemeli');
assert.equal(A.depart(proposal,12),proposal,'Değişiklik beklerken yola çıkılmamalı');
t = A.approve(proposal);
assert.equal(t.saat,'19:00');
assert.equal(t.repId,'s3');
assert.equal(t.revision,2);
t = A.challenge(A.depart(t,12,1000),1000);
assert.equal(A.verify(t,'başka-randevu','s3',t.dogrulama.kod,2000),null);
assert.equal(A.verify(t,t.id,'s1',t.dogrulama.kod,2000),null);
assert.equal(A.verify(t,t.id,'s3',t.dogrulama.kod,700000),null);
assert.equal(A.verify(A.cancel(t),t.id,'s3',t.dogrulama.kod,2000),null);
const verified = A.verify(t,t.id,'s3',t.dogrulama.kod,2000);
assert.equal(verified.durum,'gorusmede');
assert.equal(verified.dogrulama,null,'Doğrulama kodu tüketilmeli');
assert.equal(A.verify(verified,t.id,'s3',t.dogrulama.kod,2001),null);
const startedWithProposal={...verified,degisiklik:{saat:'20:00'}};
assert.equal(A.approve(startedWithProposal),startedWithProposal,'Başlayan görüşme eski öneriyle yeniden açılmamalı');
assert.equal(A.depart({...t,durum:'netlesti',degisiklik:null,demoZaman:{simdi:0,baslangic:0}},12,1000).demoZaman,null);

